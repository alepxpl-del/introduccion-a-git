# Los operadores de comparación se utilizan para comparar valores. El resultado de resulting de estas operaciones es siempre un valor booleano: True o False.
# Estos operadores son fundamentales para tomar decisiones en estructuras condicionales y bucles.
x = 5
y = 10

# Igual a #
print(x == x)
print(x == y)
print(y == y)

# Distinto que #
print(x != x)
print(x != y)
print(y != y)

# Mayor que #
print(x > x)
print(x > y)
print(y > y)

# Menor que #
print(x < x)
print(x < y)
print(y < y)

# Mayor o igual que #
print(x >= x)
print(x >= y)
print(y >= y)

# Menor o igual que #
print(x <= x)
print(x <= y)
print(y <= y)