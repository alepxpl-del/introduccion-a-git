#Python ofrece varios operadores para realizar cálculos numéricos básicos y avanzados. Estos operadores trabajan con números enteros (int) y decimales (float).

# Suma #
suma = 3 + 2
print(suma)

# Resta #
resta = 3 - 2
print(resta)

# Multiplicacion #
multiplicacion = 3 * 2
print(multiplicacion)

# Potencia #
potencia = 3 ** 2
print(potencia)

# Division (resultado float) #
division = 5 / 2
print(division)

# Division entera (resultado int) #
division_entera = 5 // 2
print(division_entera)

# Modulo #
modulo = 7 % 2
print(modulo)